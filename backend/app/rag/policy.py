"""Правила качества диалога. Здесь нет готовых ответов или продуктовых чисел.

Сведения для ответа приходят только из базы, переданной при запуске.
Правила помогают выбрать длину, следующий вопрос и необходимость проверки.
"""
from __future__ import annotations
import re
from retrieval import Dialogue, normal


def response_guidance(dialogue: Dialogue) -> str:
    """Задаёт форму ответа, а НЕ заранее определённый ответ."""
    q = normal(dialogue.last)
    all_user = normal('\n'.join(dialogue.active_user))
    rules = []
    if dialogue.history:
        rules.append('Продолжи разговор. Учитывай все сообщённые клиентом параметры; '
                     'не задавай уже отвеченный вопрос и не повторяй вступление о продукте.')
    if re.search(r'не готов|не хочу|не буду|не дам|без телефон', q) and re.search(r'телефон|контакт|номер|данн', q):
        rules.append('Клиент не согласен оставить контакты: признай отказ и продолжи содержательную '
                     'консультацию. Не собирай заявку и не проси вместо телефона другой контакт.')
    if re.search(r'какие данн|что.{0,20}подготов|что.{0,15}понадоб|с чего нач|что.{0,20}провер', q):
        rules.append('Нужен конкретный следующий шаг и необходимые данные по текущей задаче, '
                     'а не пересказ рекламы. Если данные уже названы, проверь именно их достаточность.')
    if re.search(r'хватит|достаточ|подойдет.{0,15}данн|можно.{0,12}начин', q):
        rules.append('Проверь каждое условие достаточности отдельно: период, детализацию, состав '
                     'и качество данных. Не говори безусловное «да», если часть условий не подтверждена.')
    if re.search(r'сравни|отлич|что лучше|что выбрать|либо|или', q):
        rules.append('Раздели варианты по существенному для клиента отличию и условию выбора. '
                     'Не объявляй один вариант универсально лучшим.')
    if re.search(r'стоим|цен[ауы]|сколько.*(?:стоит|плат|руб)|окуп|экономи|срок', q):
        rules.append('Покажи только относящиеся к вопросу публичные ориентиры, если они есть в базе. '
                     'Каждый ориентир — вместе с его условиями. Не рассчитывай итоговую цену, '
                     'экономию или срок объекта по одному параметру.')
    if re.search(r'персональн|договор|правомер|юридическ|согласие|ответственност', q):
        rules.append('Отдели техническое описание конкретного продукта от юридического заключения. '
                     'Не переноси режим обработки данных между разными продуктами.')
    if re.search(r'оформ.{0,15}заяв|перезвон|свяж.{0,15}менедж|коммерческ.{0,15}предлож|хочу.{0,15}менедж', q):
        rules.append('Это может быть запрос заявки: возьми контакты только из слов клиента, '
                     'запроси недостающее. Не объявляй внешнюю отправку или назначенный звонок.')
    # Приоритет уточнения выведен из состава данных в KB и публичных примеров.
    # Это направления вопроса, не подставленные ответы или сведения об объекте.
    if re.search(r'\bкрыш|кровл|\bскат|фасад|вертикальн', q) and re.search(r'панел|солнеч|станц', all_user):
        if re.search(r'стар|шифер', q):
            rules.append('Для старой кровли сначала поясни применимое ограничение из базы; '
                         'полезное уточнение — её возраст/состояние, если клиент ещё не сообщил.')
        else:
            rules.append('На вопрос о размещении ответь про допустимый вариант монтажа. '
                         'Для оценки выработки полезно уточнить регион, если он ещё не назван.')
    if re.search(r'расшир|нараст|поэтап|сначала.{0,30}потом', q) and re.search(r'солнеч|станц|панел', all_user):
        rules.append('Отдели возможность поэтапного внедрения от расчёта мощности. '
                     'Для следующего шага важны данные дневного потребления, если их ещё нет.')
    if re.search(r'вечер|ноч', all_user) and re.search(r'сетев.{0,12}станц|солнеч|панел', all_user):
        rules.append('Сопоставь выработку и время нагрузки, не забыв цель резервного питания, '
                     'если она была названа. Полезное уточнение — соотношение дневного и вечернего потребления.')
    if re.search(r'симк|sim|сим.карт', q):
        rules.append('Не смешивай поддержку оператора связи с совместимостью конкретного прибора. '
                     'Для последнего полезна модель счётчика, если она ещё неизвестна.')
    if re.search(r'цех|арендатор|магазин|склад', all_user) and not re.search(r'солнеч|панел|орэм|оптов', q):
        rules.append('В вопросе учёта раздели текущую задачу, наличие приборов и способ сбора. '
                     'Спроси только следующее неизвестное: наличие отдельных счётчиков, способ '
                     'сбора или масштаб ручного обхода. Уже известные количества не переспрашивай.')
    if re.search(r'счет|платеж|платим', q) and re.search(r'рост|вырос|больш|провер', q):
        rules.append('При разборе роста счёта отдели объём, цену и мощность. Если категория '
                     'неизвестна — уточни её; если уже названа — полезнее мощность и сравниваемые периоды.')
    if not rules:
        rules.append('Ответь непосредственно на функцию или возможность, о которой спрашивают. '
                     'При подборе для объекта спроси один важный неизвестный параметр. '
                     'Для законченного справочного ответа вопрос не требуется.')
    return '\n'.join('- '+line for line in rules)
